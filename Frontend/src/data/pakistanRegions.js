// Helper to get all locations as a flat list for search
export const getAllLocations = () => {
    const locations = ['Pakistan'];
    pakistanRegions.forEach(province => {
        locations.push(province.name);
        province.zones.forEach(zone => {
            // Add zone name if it's not too descriptive/generic
            if (!zone.name.includes('settlements') && !zone.name.includes('belt') && !zone.name.includes('Zone')) {
                locations.push(zone.name);
            }
            zone.locations.forEach(loc => {
                locations.push(loc);
                // Add sub-regions if they exist
                if (citySubRegions[loc]) {
                    citySubRegions[loc].forEach(sub => locations.push(sub));
                }
            });
        });
    });
    return [...new Set(locations)];
};
